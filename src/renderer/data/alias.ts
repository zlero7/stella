// 검색에 덧붙일 한글 별칭 (소문자로 합쳐 쓴다)
export const aliasOf = (title: string, artist = ''): string => {
  const a = artist.trim().toLowerCase(), t = title.replace(/\s*\[.*\]\s*$/, '').trim()
  const parts: string[] = []
  const has = (x: string) => new RegExp(`(^|[^a-z0-9])${x.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}($|[^a-z0-9])`).test(a) // 'eve'가 'steve' 안에서 걸리지 않게 낱말 단위로
  for (const x of Object.keys(ARTISTS)) if (has(x)) parts.push(ARTISTS[x])
  const tt = TITLES[a]
  if (tt && tt[t]) parts.push(tt[t])
  return parts.join(' ')
}
